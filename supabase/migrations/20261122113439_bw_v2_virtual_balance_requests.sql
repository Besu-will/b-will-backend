-- B-Will V2: non-monetary Balance requests with atomic withdrawal reservations.
-- These requests only adjust in-game Balance after Host review. No payment rails exist.

begin;

alter table public.bw_wallets
  add column if not exists reserved_balance bigint not null default 0;
alter table public.bw_wallets
  drop constraint if exists bw_wallets_reserved_balance_check;
alter table public.bw_wallets
  add constraint bw_wallets_reserved_balance_check
  check (reserved_balance >= 0 and reserved_balance <= balance);

create table if not exists public.bw_balance_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  username_snapshot text not null,
  request_type text not null check (request_type in ('deposit','withdraw')),
  amount bigint not null check (amount > 0),
  note text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','cancelled')),
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  processed_by uuid references auth.users(id) on delete set null,
  processing_note text,
  constraint bw_balance_requests_note_length_check
    check (note is null or char_length(note) <= 200),
  constraint bw_balance_requests_processing_note_length_check
    check (processing_note is null or char_length(processing_note) <= 200)
);

create index if not exists bw_balance_requests_user_created_idx
  on public.bw_balance_requests(user_id,created_at desc,id desc);
create index if not exists bw_balance_requests_status_created_idx
  on public.bw_balance_requests(status,created_at desc,id desc);

alter table public.bw_balance_requests enable row level security;
drop policy if exists bw_balance_requests_owner_read on public.bw_balance_requests;
create policy bw_balance_requests_owner_read
  on public.bw_balance_requests for select to authenticated
  using (user_id = (select auth.uid()));
drop policy if exists bw_balance_requests_host_read on public.bw_balance_requests;
create policy bw_balance_requests_host_read
  on public.bw_balance_requests for select to authenticated
  using ((select public.bw_is_admin()));

grant select on public.bw_balance_requests to authenticated;

alter table public.bw_ledger drop constraint if exists bw_ledger_entry_type_check;
alter table public.bw_ledger
  add constraint bw_ledger_entry_type_check
  check (entry_type = any (array[
    'starting_grant'::text,'bet'::text,'bet_cancel'::text,'win'::text,
    'admin_adjustment'::text,'request_deposit'::text,'request_withdraw'::text
  ]));

create or replace function public.bw_submit_balance_request(
  p_type text,
  p_amount bigint,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid := auth.uid();
  v_type text := lower(btrim(p_type));
  v_note text := nullif(btrim(p_note),'');
  v_username text;
  v_balance bigint;
  v_reserved bigint;
  v_request_id bigint;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if v_type not in ('deposit','withdraw') then raise exception 'Choose Deposit or Withdraw'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'Enter an amount greater than zero'; end if;
  if v_note is not null and char_length(v_note)>200 then raise exception 'Explanation must be 200 characters or fewer'; end if;

  perform pg_advisory_xact_lock(7812345601);

  select username into v_username from public.bw_profiles where user_id=v_uid;
  select balance,reserved_balance into v_balance,v_reserved
  from public.bw_wallets where user_id=v_uid for update;
  if not found then raise exception 'Player Balance account not found'; end if;

  if v_type='withdraw' then
    if v_balance-v_reserved < p_amount then
      raise exception 'Insufficient available Balance for this Withdraw request';
    end if;
    update public.bw_wallets
    set reserved_balance=reserved_balance+p_amount,updated_at=now()
    where user_id=v_uid
      and balance-reserved_balance >= p_amount
    returning balance,reserved_balance into v_balance,v_reserved;
    if not found then raise exception 'Insufficient available Balance for this Withdraw request'; end if;
  end if;

  insert into public.bw_balance_requests(
    user_id,username_snapshot,request_type,amount,note
  )
  values(v_uid,coalesce(v_username,'Player'),v_type,p_amount,v_note)
  returning id into v_request_id;

  return jsonb_build_object(
    'request_id',v_request_id,
    'request_type',v_type,
    'amount',p_amount,
    'status','pending',
    'balance',v_balance,
    'reserved_balance',v_reserved,
    'available_balance',v_balance-v_reserved
  );
end;
$function$;

create or replace function public.bw_cancel_balance_request(p_request_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid := auth.uid();
  v_request public.bw_balance_requests%rowtype;
  v_balance bigint;
  v_reserved bigint;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  perform pg_advisory_xact_lock(7812345601);

  select * into v_request
  from public.bw_balance_requests
  where id=p_request_id and user_id=v_uid
  for update;

  if not found or v_request.status<>'pending' then
    raise exception 'This request is no longer pending';
  end if;

  if v_request.request_type='withdraw' then
    update public.bw_wallets
    set reserved_balance=reserved_balance-v_request.amount,updated_at=now()
    where user_id=v_uid and reserved_balance>=v_request.amount
    returning balance,reserved_balance into v_balance,v_reserved;
    if not found then raise exception 'Balance reservation could not be released'; end if;
  else
    select balance,reserved_balance into v_balance,v_reserved
    from public.bw_wallets where user_id=v_uid;
  end if;

  update public.bw_balance_requests
  set status='cancelled',processed_at=now(),processed_by=v_uid,
      processing_note='Cancelled by player'
  where id=v_request.id and status='pending';

  return jsonb_build_object(
    'request_id',v_request.id,'status','cancelled',
    'balance',v_balance,'reserved_balance',v_reserved,
    'available_balance',v_balance-v_reserved
  );
end;
$function$;

create or replace function public.bw_get_my_requests(
  p_limit integer default 50,
  p_before_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid := auth.uid();
  v_items jsonb;
  v_next bigint;
  v_count integer;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if p_limit is null or p_limit<1 or p_limit>100 then
    raise exception 'Request page size must be between 1 and 100';
  end if;

  with page as (
    select id,request_type,amount,note,status,created_at,processed_at,processing_note
    from public.bw_balance_requests
    where user_id=v_uid and (p_before_id is null or id<p_before_id)
    order by id desc
    limit p_limit
  )
  select
    coalesce(jsonb_agg(jsonb_build_object(
      'request_id',id,'request_type',request_type,'amount',amount,
      'note',note,'status',status,'created_at',created_at,
      'processed_at',processed_at,'processing_note',processing_note
    ) order by id desc),'[]'::jsonb),
    min(id),count(*)::integer
  into v_items,v_next,v_count
  from page;

  return jsonb_build_object(
    'items',v_items,
    'next_before_id',case when v_count=p_limit then v_next else null end
  );
end;
$function$;

create or replace function public.bw_admin_list_balance_requests(
  p_status text default 'pending',
  p_limit integer default 100
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_status text := lower(coalesce(btrim(p_status),'pending'));
  v_items jsonb;
begin
  if auth.uid() is null or not exists(
    select 1 from private.bw_admins where user_id=auth.uid()
  ) then raise exception 'Host access required'; end if;

  if v_status not in ('pending','approved','rejected','cancelled','all') then
    raise exception 'Invalid request status filter';
  end if;
  if p_limit is null or p_limit<1 or p_limit>200 then
    raise exception 'Request page size must be between 1 and 200';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'request_id',q.id,'user_id',q.user_id,'username',q.username_snapshot,
    'request_type',q.request_type,'amount',q.amount,'note',q.note,
    'status',q.status,'created_at',q.created_at,'processed_at',q.processed_at,
    'processing_note',q.processing_note,
    'balance',q.balance,'reserved_balance',q.reserved_balance,
    'available_balance',case when q.balance is null then null else q.balance-q.reserved_balance end
  ) order by q.created_at desc,q.id desc),'[]'::jsonb)
  into v_items
  from (
    select br.*,w.balance,w.reserved_balance
    from public.bw_balance_requests br
    left join public.bw_wallets w on w.user_id=br.user_id
    where v_status='all' or br.status=v_status
    order by br.created_at desc,br.id desc
    limit p_limit
  ) q;

  return jsonb_build_object('requests',v_items);
end;
$function$;

create or replace function public.bw_admin_review_balance_request(
  p_request_id bigint,
  p_decision text,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_admin uuid := auth.uid();
  v_decision text := lower(btrim(p_decision));
  v_reason text := nullif(btrim(p_reason),'');
  v_request public.bw_balance_requests%rowtype;
  v_balance bigint;
  v_reserved bigint;
  v_entry_type text;
  v_entry_amount bigint;
begin
  if v_admin is null or not exists(
    select 1 from private.bw_admins where user_id=v_admin
  ) then raise exception 'Host access required'; end if;
  if v_decision not in ('approve','reject') then raise exception 'Decision must be approve or reject'; end if;
  if v_reason is not null and char_length(v_reason)>200 then raise exception 'Reason must be 200 characters or fewer'; end if;
  if v_decision='reject' and v_reason is null then raise exception 'A reason is required when rejecting a request'; end if;

  perform pg_advisory_xact_lock(7812345601);

  select * into v_request from public.bw_balance_requests
  where id=p_request_id for update;
  if not found or v_request.status<>'pending' then
    raise exception 'This request is no longer pending';
  end if;
  if v_request.user_id is null then raise exception 'The player account no longer exists'; end if;

  select balance,reserved_balance into v_balance,v_reserved
  from public.bw_wallets where user_id=v_request.user_id for update;
  if not found then raise exception 'Player Balance account not found'; end if;

  if v_decision='approve' then
    if v_request.request_type='deposit' then
      update public.bw_wallets
      set balance=balance+v_request.amount,updated_at=now()
      where user_id=v_request.user_id
      returning balance,reserved_balance into v_balance,v_reserved;
      v_entry_type:='request_deposit';
      v_entry_amount:=v_request.amount;
    else
      update public.bw_wallets
      set balance=balance-v_request.amount,
          reserved_balance=reserved_balance-v_request.amount,
          updated_at=now()
      where user_id=v_request.user_id
        and balance>=v_request.amount
        and reserved_balance>=v_request.amount
      returning balance,reserved_balance into v_balance,v_reserved;
      if not found then raise exception 'Reserved Balance could not be deducted safely'; end if;
      v_entry_type:='request_withdraw';
      v_entry_amount:=-v_request.amount;
    end if;

    insert into public.bw_ledger(user_id,entry_type,amount,balance_after,reference)
    values(v_request.user_id,v_entry_type,v_entry_amount,v_balance,
      'balance_request:'||v_request.id::text);
  elsif v_request.request_type='withdraw' then
    update public.bw_wallets
    set reserved_balance=reserved_balance-v_request.amount,updated_at=now()
    where user_id=v_request.user_id and reserved_balance>=v_request.amount
    returning balance,reserved_balance into v_balance,v_reserved;
    if not found then raise exception 'Balance reservation could not be released'; end if;
  end if;

  update public.bw_balance_requests
  set status=case when v_decision='approve' then 'approved' else 'rejected' end,
      processed_at=now(),processed_by=v_admin,processing_note=v_reason
  where id=v_request.id and status='pending';

  return jsonb_build_object(
    'request_id',v_request.id,
    'status',case when v_decision='approve' then 'approved' else 'rejected' end,
    'balance',v_balance,'reserved_balance',v_reserved,
    'available_balance',v_balance-v_reserved
  );
end;
$function$;

create or replace function public.bw_place_bet(p_slot smallint,p_color text,p_stake bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid := auth.uid();
  v_state jsonb;
  v_round_id bigint;
  v_balance bigint;
  v_reserved bigint;
  v_min bigint;
  v_max bigint;
  v_closes timestamptz;
  v_name text;
  v_bet public.bw_bets%rowtype;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if p_slot not in (1,2) then raise exception 'Invalid betting slot'; end if;
  if p_color not in ('green','orange','blue') then raise exception 'Invalid colour'; end if;

  select min_stake,max_stake into v_min,v_max from private.bw_settings where id=1;
  if p_stake<v_min or p_stake>v_max then raise exception 'Stake is outside the allowed range'; end if;

  v_state:=public.bw_tick();
  v_round_id:=(v_state->'round'->>'id')::bigint;
  perform pg_advisory_xact_lock(7812345601);

  select closes_at into v_closes from public.bw_rounds
  where id=v_round_id and status='open' for update;
  if not found or v_closes<=clock_timestamp() then raise exception 'Betting is closed for this round'; end if;

  select balance,reserved_balance into v_balance,v_reserved
  from public.bw_wallets where user_id=v_uid for update;
  if v_balance-v_reserved<p_stake then raise exception 'Insufficient available Balance'; end if;

  if exists(select 1 from public.bw_bets
    where round_id=v_round_id and user_id=v_uid and slot_index=p_slot and status='placed') then
    raise exception 'This betting slot is already in use';
  end if;

  select username into v_name from public.bw_profiles where user_id=v_uid;
  update public.bw_wallets set balance=balance-p_stake,updated_at=now()
  where user_id=v_uid and balance-reserved_balance>=p_stake
  returning balance,reserved_balance into v_balance,v_reserved;
  if not found then raise exception 'Insufficient available Balance'; end if;

  insert into public.bw_ledger(user_id,entry_type,amount,balance_after,reference)
  values(v_uid,'bet',-p_stake,v_balance,'round:'||v_round_id::text||':slot:'||p_slot::text);

  insert into public.bw_bets(round_id,user_id,username_snapshot,slot_index,color,stake)
  values(v_round_id,v_uid,coalesce(v_name,'Player'),p_slot,p_color,p_stake)
  returning * into v_bet;

  update public.bw_rounds set total_pot=total_pot+p_stake where id=v_round_id;

  return jsonb_build_object(
    'bet',jsonb_build_object('id',v_bet.id,'round_id',v_bet.round_id,
      'slot_index',v_bet.slot_index,'color',v_bet.color,'stake',v_bet.stake,'status',v_bet.status),
    'balance',v_balance,'reserved_balance',v_reserved,
    'available_balance',v_balance-v_reserved
  );
end;
$function$;

create or replace function public.bw_get_state()
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid:=auth.uid();
  v_state jsonb;
  v_wallet bigint;
  v_reserved bigint;
  v_profile text;
  v_round_id bigint;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  v_state:=public.bw_tick();
  v_round_id:=(v_state->'round'->>'id')::bigint;

  select balance,reserved_balance into v_wallet,v_reserved
  from public.bw_wallets where user_id=v_uid;
  select username into v_profile from public.bw_profiles where user_id=v_uid;

  return v_state || jsonb_build_object(
    'wallet',v_wallet,
    'reserved_balance',v_reserved,
    'available_balance',v_wallet-v_reserved,
    'username',v_profile,
    'my_bets',coalesce((
      select jsonb_agg(jsonb_build_object(
        'id',id,'slot_index',slot_index,'color',color,'stake',stake,'status',status,'payout',payout
      ) order by slot_index)
      from public.bw_bets
      where round_id=v_round_id and user_id=v_uid and status='placed'
    ),'[]'::jsonb),
    'recent_rounds',coalesce((
      select jsonb_agg(jsonb_build_object(
        'id',id,'winner_color',winner_color,'total_pot',total_pot,'dead_round',dead_round,
        'server_seed_hash',server_seed_hash,'server_seed_reveal',server_seed_reveal,'client_seed',client_seed
      ) order by id desc)
      from (select * from public.bw_rounds where status='settled' order by id desc limit 10) h
    ),'[]'::jsonb)
  );
end;
$function$;

create or replace function public.bw_cancel_bet(p_bet_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_uid uuid:=auth.uid();
  v_bet public.bw_bets%rowtype;
  v_round public.bw_rounds%rowtype;
  v_balance bigint;
  v_reserved bigint;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if p_bet_id is null or p_bet_id<=0 then raise exception 'Invalid bet'; end if;
  perform pg_advisory_xact_lock(7812345601);

  select * into v_bet from public.bw_bets
  where id=p_bet_id and user_id=v_uid for update;
  if not found or v_bet.status<>'placed' then raise exception 'This bet can no longer be cancelled'; end if;

  select * into v_round from public.bw_rounds where id=v_bet.round_id for update;
  if not found or v_round.status<>'open' or v_round.closes_at<=clock_timestamp() then
    raise exception 'Betting is closed; cancellation is unavailable';
  end if;

  update public.bw_wallets
  set balance=balance+v_bet.stake,updated_at=now()
  where user_id=v_uid returning balance,reserved_balance into v_balance,v_reserved;

  update public.bw_rounds
  set total_pot=total_pot-v_bet.stake
  where id=v_bet.round_id and total_pot>=v_bet.stake;
  if not found then raise exception 'Round pot reconciliation failed'; end if;

  update public.bw_bets set status='cancelled',payout=0
  where id=v_bet.id and status='placed';

  insert into public.bw_ledger(user_id,entry_type,amount,balance_after,reference)
  values(v_uid,'bet_cancel',v_bet.stake,v_balance,'bet:'||v_bet.id::text||':cancel');

  return jsonb_build_object(
    'bet_id',v_bet.id,'round_id',v_bet.round_id,'slot_index',v_bet.slot_index,
    'stake_returned',v_bet.stake,'balance',v_balance,
    'reserved_balance',v_reserved,'available_balance',v_balance-v_reserved,'status','cancelled'
  );
end;
$function$;

create or replace function public.bw_admin_adjust(p_user_id uuid,p_amount bigint,p_reason text)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_balance bigint;
  v_reserved bigint;
  v_reason text:=btrim(p_reason);
begin
  if auth.uid() is null or not exists(select 1 from private.bw_admins where user_id=auth.uid()) then
    raise exception 'Host access required';
  end if;
  if p_amount is null or p_amount=0 or abs(p_amount)>1000000 then raise exception 'Invalid adjustment amount'; end if;
  if v_reason is null or char_length(v_reason)<4 or char_length(v_reason)>200 then
    raise exception 'Provide a reason between 4 and 200 characters';
  end if;

  perform pg_advisory_xact_lock(7812345601);
  perform 1 from public.bw_wallets where user_id=p_user_id for update;
  if not found then raise exception 'Player wallet not found'; end if;

  update public.bw_wallets
  set balance=balance+p_amount,updated_at=now()
  where user_id=p_user_id and balance+p_amount>=reserved_balance
  returning balance,reserved_balance into v_balance,v_reserved;
  if not found then raise exception 'Adjustment would reduce Balance below reserved Balance'; end if;

  insert into public.bw_ledger(user_id,entry_type,amount,balance_after,reference)
  values(p_user_id,'admin_adjustment',p_amount,v_balance,v_reason);

  return jsonb_build_object(
    'user_id',p_user_id,'balance',v_balance,'reserved_balance',v_reserved,
    'available_balance',v_balance-v_reserved
  );
end;
$function$;

create or replace function public.bw_admin_dashboard()
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if auth.uid() is null or not exists(select 1 from private.bw_admins where user_id=auth.uid()) then
    raise exception 'Host access required';
  end if;

  return jsonb_build_object(
    'player_count',(select count(*) from public.bw_profiles),
    'round_count',(select count(*) from public.bw_rounds where status='settled'),
    'house_balance',(select balance from private.bw_house_accounts where id=1),
    'pending_requests',(select count(*) from public.bw_balance_requests where status='pending'),
    'players',coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id',p.user_id,'username',p.username,
        'balance',w.balance,'reserved_balance',w.reserved_balance,
        'available_balance',w.balance-w.reserved_balance,'created_at',p.created_at
      ) order by p.created_at desc)
      from public.bw_profiles p join public.bw_wallets w using(user_id)
    ),'[]'::jsonb),
    'recent_rounds',coalesce((
      select jsonb_agg(jsonb_build_object(
        'id',id,'winner_color',winner_color,'total_pot',total_pot,
        'house_amount',house_amount,'dead_round',dead_round,'settled_at',settled_at
      ) order by id desc)
      from (select * from public.bw_rounds where status='settled' order by id desc limit 20) r
    ),'[]'::jsonb)
  );
end;
$function$;

